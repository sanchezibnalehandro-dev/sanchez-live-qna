create table if not exists public.audience_choice_polls (
  id bigint generated by default as identity primary key,
  event_key text not null unique,
  poll_key text not null unique,
  title text not null,
  status text not null default 'draft'
    check (status in ('draft', 'open', 'closed', 'revealed')),
  created_at timestamptz not null default now(),
  constraint audience_choice_event_key_nonempty check (length(btrim(event_key)) > 0),
  constraint audience_choice_poll_key_nonempty check (length(btrim(poll_key)) > 0)
);

create table if not exists public.audience_choice_votes (
  id bigint generated by default as identity primary key,
  poll_id bigint not null references public.audience_choice_polls(id) on delete cascade,
  guest_id uuid not null,
  own_team smallint not null check (own_team between 1 and 5),
  team_no smallint not null check (team_no between 1 and 5),
  created_at timestamptz not null default now(),
  constraint audience_choice_no_self_vote check (own_team <> team_no),
  constraint audience_choice_one_browser_vote unique (poll_id, guest_id)
);

create index if not exists audience_choice_votes_poll_team_idx
  on public.audience_choice_votes (poll_id, team_no);

-- Defense in depth: no direct guest reads/writes to tables.
alter table public.audience_choice_polls enable row level security;
alter table public.audience_choice_votes enable row level security;
revoke all on table public.audience_choice_polls from public, anon, authenticated;
revoke all on table public.audience_choice_votes from public, anon, authenticated;

