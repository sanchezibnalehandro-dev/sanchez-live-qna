create or replace function public.audience_choice_get(
  p_poll_key text, p_guest_id uuid
) returns jsonb
language plpgsql security definer set search_path = ''
as $$
declare
  v_id bigint;
  v_title text;
  v_status text;
  v_voted boolean;
begin
  select id, title, status into v_id, v_title, v_status
  from public.audience_choice_polls where poll_key = btrim(p_poll_key);
  if not found then return null; end if;
  select exists(
    select 1 from public.audience_choice_votes
    where poll_id = v_id and guest_id = p_guest_id
  ) into v_voted;
  return jsonb_build_object(
    'title', v_title, 'status', v_status, 'already_voted', v_voted
  );
end;
$$;

create or replace function public.audience_choice_submit(
  p_poll_key text, p_guest_id uuid, p_team_no smallint
) returns boolean
language plpgsql security definer set search_path = ''
as $$
declare
  v_id bigint;
  v_status text;
  v_inserted integer;
begin
  if p_guest_id is null or p_team_no is null or p_team_no not between 1 and 5 then
    raise exception 'Invalid vote';
  end if;
  -- Locks the state during insertion; closing waits for ongoing votes to finish.
  select id, status into v_id, v_status
  from public.audience_choice_polls
  where poll_key = btrim(p_poll_key)
  for share;
  if not found or v_status <> 'open' then
    raise exception 'Voting is closed';
  end if;
  insert into public.audience_choice_votes(poll_id, guest_id, team_no)
    values (v_id, p_guest_id, p_team_no)
    on conflict (poll_id, guest_id) do nothing;
  get diagnostics v_inserted = row_count;
  return v_inserted = 1;
end;
$$;

create or replace function public.audience_choice_admin_state(
  p_poll_key text
) returns jsonb
language plpgsql security definer set search_path = ''
as $$
declare
  v_id bigint;
  v_status text;
  v_title text;
  v_counts jsonb;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  select id, status, title into v_id, v_status, v_title
  from public.audience_choice_polls where poll_key = btrim(p_poll_key);
  if not found then return null; end if;
  select jsonb_agg(
    jsonb_build_object(
      'team_no', n,
      'votes', (select count(*) from public.audience_choice_votes v
                where v.poll_id = v_id and v.team_no = n)
    ) order by n
  ) into v_counts
  from generate_series(1, 5) as n;
  return jsonb_build_object(
    'title', v_title, 'status', v_status, 'counts', v_counts
  );
end;
$$;

create or replace function public.audience_choice_admin_status(
  p_poll_key text, p_status text
) returns text
language plpgsql security definer set search_path = ''
as $$
declare
  v_status text;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if p_status not in ('draft','open','closed','revealed') then
    raise exception 'Invalid status';
  end if;
  update public.audience_choice_polls
  set status = p_status
  where poll_key = btrim(p_poll_key)
  returning status into v_status;
  if not found then raise exception 'Poll not found'; end if;
  return v_status;
end;
$$;

revoke all on function public.audience_choice_get(text, uuid) from public;
