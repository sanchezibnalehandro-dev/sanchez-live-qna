-- Lightweight state check for the existing welcome.html guest entrance.
-- Never exposes vote counts, browser IDs, or the caller's team.
create or replace function public.audience_choice_event_status(p_event_key text)
returns jsonb
language sql stable security definer set search_path = ''
as $$
  select jsonb_build_object('status', p.status, 'poll_key', p.poll_key)
    from public.audience_choice_polls p
   where p.event_key = btrim(p_event_key)
$$;

-- Guest page: only poll status and whether THIS browser already voted.
create or replace function public.audience_choice_get(
  p_poll_key text, p_guest_id uuid
) returns jsonb
language plpgsql stable security definer set search_path = ''
as $$
declare
  v_id bigint;
  v_title text;
  v_status text;
  v_voted boolean;
begin
  if p_guest_id is null then raise exception 'Invalid browser session'; end if;
  select id, title, status into v_id, v_title, v_status
    from public.audience_choice_polls
   where poll_key = btrim(p_poll_key);
  if not found then return null; end if;

  select exists (
    select 1 from public.audience_choice_votes
     where poll_id = v_id and guest_id = p_guest_id
  ) into v_voted;

  return jsonb_build_object(
    'title', v_title, 'status', v_status, 'already_voted', v_voted
  );
end;
$$;

-- One atomic submission; no editing and no self-votes.
-- Unique constraint protects against concurrent double taps, not just UI checks.
create or replace function public.audience_choice_submit(
  p_poll_key text,
  p_guest_id uuid,
  p_own_team smallint,
  p_team_no smallint
) returns boolean
language plpgsql volatile security definer set search_path = ''
as $$
declare
  v_id bigint;
  v_status text;
  v_inserted integer;
begin
  if p_guest_id is null
     or p_own_team is null or p_team_no is null
     or p_own_team not between 1 and 5
     or p_team_no not between 1 and 5
     or p_own_team = p_team_no then
    raise exception 'Invalid team choice';
  end if;

  -- Concurrent Close waits for in-flight votes; afterward all new votes fail.
  select id, status into v_id, v_status
    from public.audience_choice_polls
   where poll_key = btrim(p_poll_key)
   for share;
  if not found or v_status <> 'open' then
    raise exception 'Voting is closed';
  end if;

  insert into public.audience_choice_votes(poll_id, guest_id, own_team, team_no)
  values (v_id, p_guest_id, p_own_team, p_team_no)
  on conflict (poll_id, guest_id) do nothing;

  get diagnostics v_inserted = row_count;
  return v_inserted = 1;
end;
$$;

-- The existing ModeratorLive Supabase Auth is for staff accounts.
-- No separate participant auth or extra per-team credentials are introduced.
-- Admin endpoints do NOT grant access to anon; live guests never see counts.
create or replace function public.audience_choice_admin_state(p_poll_key text)
returns jsonb
language plpgsql stable security definer set search_path = ''
as $$
declare
  v_id bigint;
  v_status text;
  v_title text;
  v_counts jsonb;
begin
  if auth.uid() is null then raise exception 'Staff sign-in required'; end if;
  select id, status, title into v_id, v_status, v_title
    from public.audience_choice_polls where poll_key = btrim(p_poll_key);
  if not found then return null; end if;

  select jsonb_agg(
    jsonb_build_object(
      'team_no', n,
      'votes', (select count(*) from public.audience_choice_votes v
                where v.poll_id = v_id and v.team_no = n)
    ) order by n
  ) into v_counts
  from generate_series(1, 5) as n;

  return jsonb_build_object(
    'title', v_title, 'status', v_status, 'counts', v_counts
  );
end;
$$;

create or replace function public.audience_choice_admin_status(
  p_poll_key text, p_status text
) returns text
language plpgsql volatile security definer set search_path = ''
as $$
declare
  v_status text;
begin
  if auth.uid() is null then raise exception 'Staff sign-in required'; end if;
  if p_status is null or p_status not in ('draft', 'open', 'closed', 'revealed') then
    raise exception 'Invalid status';
  end if;
  update public.audience_choice_polls
     set status = p_status
   where poll_key = btrim(p_poll_key)
  returning status into v_status;
  if not found then raise exception 'Poll not found'; end if;
  return v_status;
end;
$$;

